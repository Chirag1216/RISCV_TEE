#!/usr/bin/env python3
"""
Derive the verifier's policy from CLEAN flight data, and write verifier/policy.h.

Use the calibration sequences only (for EuRoC: MH_01 .. MH_05). The test
sequences (V1_*, V2_*) must not be used here, so the thresholds are fixed
before the test flights are seen.

    python3 tools/calibrate.py data/MH_01.txt data/MH_02.txt ... --write

Rules:
    v_max      = 1.5 x the fastest 20 Hz step seen in the calibration data
    eps        = 50 mm
    geofence   = bounding box of the calibration flights + 1 m on every side
"""
import argparse
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from traj import load_tum, resample, speeds, DT

ap = argparse.ArgumentParser()
ap.add_argument("files", nargs="+")
ap.add_argument("--fence-from", nargs="+", default=None,
                help="optional separate trajectory files for geofence bounds")
ap.add_argument("--write", action="store_true", help="write verifier/policy.h")
ap.add_argument("--speed-margin", type=float, default=1.5)
ap.add_argument("--fence-margin-m", type=float, default=1.0)
ap.add_argument("--eps-mm", type=int, default=50)
args = ap.parse_args()

peak = 0.0
lo = [math.inf] * 3
hi = [-math.inf] * 3
total = 0
for path in args.files:
    s = resample(load_tum(path))
    v = speeds(s)
    peak = max(peak, max(v))
    if args.fence_from is None:
        for p in s:
            for k in range(3):
                lo[k] = min(lo[k], p[1 + k])
                hi[k] = max(hi[k], p[1 + k])
    total += len(s)
    print(f"{path}: {len(s)} samples at 20 Hz, peak speed {max(v):.2f} m/s, "
          f"x [{min(q[1] for q in s):.1f}, {max(q[1] for q in s):.1f}] "
          f"y [{min(q[2] for q in s):.1f}, {max(q[2] for q in s):.1f}] "
          f"z [{min(q[3] for q in s):.1f}, {max(q[3] for q in s):.1f}] m")

if args.fence_from is not None:
    for path in args.fence_from:
        s = resample(load_tum(path))
        for p in s:
            for k in range(3):
                lo[k] = min(lo[k], p[1 + k])
                hi[k] = max(hi[k], p[1 + k])

v_max = int(math.ceil(peak * args.speed_margin * 1000))          # mm/s
m = args.fence_margin_m
fence = [int(math.floor((lo[k] - m) * 1000)) for k in range(3)], [int(math.ceil((hi[k] + m) * 1000)) for k in range(3)]
d_min = v_max * DT + args.eps_mm

print()
print(f"peak speed over all files : {peak:.2f} m/s")
print(f"V_MAX_MM_S                : {v_max}  ({v_max/1000:.2f} m/s)")
print(f"EPS_MM                    : {args.eps_mm}")
print(f"geofence x                : [{fence[0][0]}, {fence[1][0]}] mm")
print(f"geofence y                : [{fence[0][1]}, {fence[1][1]}] mm")
print(f"geofence z                : [{fence[0][2]}, {fence[1][2]}] mm")
print(f"detectability bound d_min : {d_min:.0f} mm  (= V_MAX * 50 ms + EPS)")

if args.write:
    text = f"""#ifndef POLICY_H
#define POLICY_H

/*
 * Safety policy. GENERATED by tools/calibrate.py from:
 *   {', '.join(os.path.basename(p) for p in args.files)}
 * peak speed {peak:.2f} m/s, speed margin x{args.speed_margin}, fence margin {m} m.
 * Rebuild the monitor after changing this file (the verifier is embedded in it).
 */

#define MIN_PERIOD_US   20000       /* rate limit: at most one command every 20 ms (50 Hz) */

#define V_MAX_MM_S      {v_max:<8}    /* maximum speed                                       */
#define EPS_MM          {args.eps_mm:<8}    /* tolerance added to every step limit                 */
#define DT_CAP_US       200000      /* a step may use at most 200 ms of travel time        */

/* Geofence: an axis-aligned box, millimetres. */
#define FENCE_X_MIN     ({fence[0][0]})
#define FENCE_X_MAX     ({fence[1][0]})
#define FENCE_Y_MIN     ({fence[0][1]})
#define FENCE_Y_MAX     ({fence[1][1]})
#define FENCE_Z_MIN     ({fence[0][2]})
#define FENCE_Z_MAX     ({fence[1][2]})

#endif
"""
    with open("verifier/policy.h", "w") as f:
        f.write(text)
    print("\nwrote verifier/policy.h  ->  run `make` to rebuild the monitor with it")
